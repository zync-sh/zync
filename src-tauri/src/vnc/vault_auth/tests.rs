use super::*;
use serde_json::json;

#[test]
fn saved_links_require_exact_unique_endpoint_and_valid_ids() {
    let profile = json!({
        "id": "desk",
        "host": "vnc.example.test",
        "port": 5901,
        "credentialId": "local-credential:1"
    });
    let settings = json!({"vncProfiles": [profile.clone()]});
    assert_eq!(
        saved_credential_id(&settings, "desk", "vnc.example.test", 5901),
        Some("local-credential:1")
    );
    assert!(saved_credential_id(&settings, "desk", "other.example.test", 5901).is_none());
    assert!(saved_credential_id(&settings, "desk", "vnc.example.test", 5902).is_none());
    assert!(saved_credential_id(&settings, "absent", "vnc.example.test", 5901).is_none());
    let duplicate = json!({"vncProfiles": [profile.clone(), profile.clone()]});
    assert!(saved_credential_id(&duplicate, "desk", "vnc.example.test", 5901).is_none());
    let mut invalid = settings;
    invalid["vncProfiles"][0]["credentialId"] = json!("../bad");
    assert!(saved_credential_id(&invalid, "desk", "vnc.example.test", 5901).is_none());
    assert!(profile_id_is_valid("Desk_123-A"));
    assert!(!profile_id_is_valid("../desk"));
    assert!(!profile_id_is_valid(&"x".repeat(129)));
}

#[test]
fn reads_only_shared_passwords_by_logical_id_from_an_unlocked_vault() {
    let directory = tempfile::tempdir().unwrap();
    let mut vault = VaultService::new(directory.path().into());
    vault
        .initialize("isolated fixture passphrase", false)
        .unwrap();
    let vnc = vault
        .item_create_with_logical_id("Desktop", "vnc-password", "zyncpass", None, Some("vnc"))
        .unwrap();
    let ssh = vault
        .item_create_with_logical_id("Shell", "ssh-password", "ssh-secret", None, Some("ssh"))
        .unwrap();
    vault
        .item_create_with_logical_id("Token", "api-token", "token-secret", None, Some("token"))
        .unwrap();
    assert!(linked_key(&vault, "vnc").is_some_and(|key| *key == *password_key("zyncpass")));
    assert!(linked_key(&vault, &vnc.id).is_none());
    assert!(linked_key(&vault, "ssh").is_some_and(|key| *key == *password_key("ssh-secret")));
    assert!(linked_key(&vault, &ssh.id).is_none());
    assert!(linked_key(&vault, "token").is_none());
    assert!(linked_key(&vault, "missing").is_none());
    vault.lock();
    assert!(linked_key(&vault, "vnc").is_none());
}

#[test]
fn des_challenges_match_bundled_viewer_padding_and_utf16_truncation() {
    // Vectors were generated by the bundled noVNC DES implementation.
    for (password, expected) in [
        ("ab", 0x0cfd685c305ae51e45fd92f615454860_u128),
        ("aé€🦊bcdignored", 0x6a584e07faae0d99b4f3e8b1ac3823e4_u128),
    ] {
        let mut challenge = 0x00112233445566778899aabbccddeeff_u128.to_be_bytes();
        encrypt_challenge(password_key(password), &mut challenge);
        assert_eq!(challenge, expected.to_be_bytes());
    }
}
